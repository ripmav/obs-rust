//! CRC-32 and BLAKE2b (P1-10; spec S-055 U1).
//!
//! - `calc_crc32` is the Rust side of `libobs/util/crc32.c`
//!   (S-055-R01/R02), table-driven IEEE CRC-32 via `crc32fast`.
//! - `blake2b_512` is the Rust side of the vendored `deps/blake2`
//!   (blake2b-512); the frontend keeps the C copy until Phase 6
//!   (P6-32 / P6-23), no libobs caller exists.

use crc32fast::Hasher;

/// S-055-R01/R02 — the C `calc_crc32(crc, buf, size)`.
///
/// Standard CRC-32 (IEEE 802.3: reflected, polynomial `0xEDB88320`,
/// table driven). The finished previous result may be passed as `crc`
/// to continue a checksum; an empty slice returns `crc` unchanged
/// (C: `size == 0` may have `buf == NULL`). Any seed is allowed.
#[must_use]
pub fn calc_crc32(crc: u32, buf: &[u8]) -> u32 {
    let mut hasher = Hasher::new_with_initial(crc);
    hasher.update(buf);
    hasher.finalize()
}

/// BLAKE2b-512 over `data` (64-byte digest).
#[must_use]
pub fn blake2b_512(data: &[u8]) -> [u8; 64] {
    use blake2::digest::{Digest, Update};
    let mut hasher = blake2::Blake2b512::new();
    Update::update(&mut hasher, data);
    hasher.finalize().into()
}

