#!/usr/bin/env python3
"""Regenerate crates/obs-hotkey-names/src/table.inc from the normative
key-name vector (S-024 M4: the vector is the normative table)."""
import re
import sys

VEC = "test/conformance/vectors/helpers/hotkeys-fallback-table.expected"
OUT = "crates/obs-hotkey-names/src/table.inc"

entries = []
for ln in open(VEC):
    m = re.match(r"^(\d+) (\S+) \1$", ln.strip())
    if m:
        entries.append((int(m.group(1)), m.group(2)))
assert len(entries) == 636, f"expected 636 entries, got {len(entries)}"
assert [i for i, _ in entries] == list(range(636)), "ids must be 0..636 in order"

out = [
    "// GENERATED by tools/gen_hotkey_names.py from",
    "// test/conformance/vectors/helpers/hotkeys-fallback-table.expected",
    "// (the normative key-name table, S-024 M4).",
    "",
    "pub const KEY_NAMES: [&str; 636] = [",
]
for i in range(0, 636, 4):
    row = ", ".join(f'"{n}"' for _, n in entries[i : i + 4])
    out.append(f"    {row}," if i + 4 < 636 else f"    {row}")
out.append("];")
open(OUT, "w").write("\n".join(out) + "\n")
print(f"wrote {OUT} ({len(entries)} entries)")
