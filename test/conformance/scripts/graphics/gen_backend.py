#!/usr/bin/env python3
"""Generates test/conformance/gen/graphics_backend_gen.c: a tracing fake for every function pointer
of struct gs_exports (Linux variant) that graphics_backend.c does not implement by hand.

usage: gen_backend.py <repo root>
Hand-written overrides are discovered by scanning graphics_backend.c for the marker  FAKE(name).
"""
import re, sys, os

root = sys.argv[1]
hdr = open(os.path.join(root, "libobs/graphics/graphics-internal.h")).read()
body = hdr.split("struct gs_exports {", 1)[1].split("\n};", 1)[0]

# keep only the common part and the Linux branch of the platform #if
out, mode = [], "common"
for line in body.split("\n"):
    s = line.strip()
    if s.startswith("#ifdef __APPLE__") or s.startswith("#elif _WIN32"):
        mode = "skip"; continue
    if s.startswith("#elif defined(__linux__)"):
        mode = "common"; continue
    if s.startswith("#endif"):
        mode = "common"; continue
    if mode == "common":
        out.append(line)
body = "\n".join(out)
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
stmts = [re.sub(r"\s+", " ", x).strip() for x in body.split(";") if x.strip()]

hand = set(re.findall(r"FAKE\((\w+)\)", open(os.path.join(root, "test/conformance/gen/graphics_backend.c")).read()))

def split_args(a):
    res, depth, cur = [], 0, ""
    for ch in a:
        if ch == "(": depth += 1
        if ch == ")": depth -= 1
        if ch == "," and depth == 0:
            res.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip(): res.append(cur.strip())
    return res

members = []
for st in stmts:
    m = re.match(r"^(.*?)\(\*(\w+)\)\((.*)\)$", st)
    if not m: continue
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    members.append((ret, name, [] if args in ("void", "") else split_args(args)))

def parse_arg(a):
    fm = re.match(r"^(.*?)\(\*(\w+)\)\(.*\)$", a)
    if fm: return ("fn", fm.group(2), a.replace("(*" + fm.group(2) + ")", "(*" + fm.group(2) + ")"))
    am = re.match(r"^(.*?)(\w+)\[(\d+)\]$", a)
    if am: return (am.group(1).strip() + " *", am.group(2), None)
    m = re.match(r"^(.*?)(\w+)$", a)
    ty = m.group(1).strip(); nm = m.group(2)
    # "struct gs_rect *rect": the star belongs to the type
    return (ty, nm, None)

def fmt_stmt(ty, nm):
    t = re.sub(r"\s+", " ", ty).replace(" *", " *")
    if ty == "fn": return f'tr_fn("{nm}", {nm});'
    if t.endswith("*"):
        if t in ("const char *", "char *"): return f'tr_str("{nm}", {nm});'
        return f'tr_ptr("{nm}", (const void *){nm});'
    if t == "bool": return f'tr_bool("{nm}", {nm});'
    if t in ("float", "double"): return f'tr_dbl("{nm}", {nm});'
    if t in ("uint64_t", "size_t"): return f'tr_u64("{nm}", {nm});'
    if t in ("int",) or t.startswith("enum"): return f'tr_i64("{nm}", (long long){nm});'
    return f'tr_u64("{nm}", (unsigned long long){nm});'

c = ['/* GENERATED by scripts/graphics/gen_backend.py -- do not edit. Test tooling, not part of libobs. */',
     '#include "graphics_backend.h"', '']
table = []
for ret, name, args in members:
    table.append(name)
    if name in hand:
        c.append(f"extern void FAKE_{name}(void);")
        continue
    parsed = [parse_arg(a) for a in args]
    sig = list(args)
    c.append(f'{ret}{"" if ret.endswith("*") else " "}FAKE_{name}({", ".join(sig) if sig else "void"})')
    c.append("{")
    c.append(f'\ttr_begin("{name}");')
    for (ty, nm, full) in parsed:
        if nm == "device" and "gs_device_t" in ty:
            c.append(f"\t(void){nm};")  # the device handle is implied; keep traces short
            continue
        c.append("\t" + fmt_stmt(ty, nm))
    c.append("\ttr_end();")
    rt = re.sub(r"\s+", " ", ret)
    if rt == "void": pass
    elif rt == "bool": c.append(f'\treturn ret_bool("{name}");')
    elif rt == "float": c.append(f'\treturn (float)ret_dbl("{name}");')
    elif rt == "const char *": c.append(f'\treturn ret_str("{name}");')
    elif rt.endswith("*"):
        if rt == "void *": c.append(f'\treturn ret_ptr("{name}", "dev");')
        else: c.append(f'\treturn (void *)ret_ptr("{name}", "{name}");')
    elif rt == "int" or rt.startswith("enum"): c.append(f'\treturn ({rt})ret_i64("{name}");')
    else: c.append(f'\treturn ({rt})ret_u64("{name}");')
    c.append("}\n")

c.append("/* function table used by the fake os_dlsym() */")
c.append("const struct fake_sym fake_symtab[] = {")
for n in table:
    c.append(f'\t{{"{n}", (void *)FAKE_{n}}},')
c.append("\t{NULL, NULL}};")
open(os.path.join(root, "test/conformance/gen/graphics_backend_gen.c"), "w").write("\n".join(c) + "\n")
print(len(table), "exports,", len(hand), "hand-written")

# ---- symbol table for the script language: every GS_* enumerator and numeric GS_* #define of graphics.h ----
gh = open(os.path.join(root, "libobs/graphics/graphics.h")).read()
gh = re.sub(r"/\*.*?\*/", "", gh, flags=re.S)
gh = gh.replace("\\\n", " ")
names = []
for blk in re.findall(r"\benum\s+\w+\s*\{(.*?)\}", gh, flags=re.S):
    for part in blk.split(","):
        m = re.match(r"\s*(GS_\w+)", part)
        if m: names.append(m.group(1))
for nm, val in re.findall(r"^\s*#\s*define\s+(GS_\w+)\s+(.*)$", gh, flags=re.M):
    if re.match(r"^\(?-?\d+\)?$|^\(\d+\s*<<\s*\d+\)$|^\(1 << \d+\)\s*\w*", val.strip()) and nm not in names:
        names.append(nm)
syms = ['/* GENERATED by scripts/graphics/gen_backend.py -- do not edit. */']
for n in names:
    syms.append(f'{{"{n}", (long long)({n})}},')
open(os.path.join(root, "test/conformance/gen/graphics_syms.inc"), "w").write("\n".join(syms) + "\n")
print(len(names), "symbols")
